  var RULES = null;
  function esc(s){ return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
  function compile(){
    RULES = [];
    for (var i = 0; i < T.length; i++) {
      var en = norm(T[i][0]), parts = en.split(/\{\d+\}/), ids = [], m, re = /\{(\d+)\}/g;
      while ((m = re.exec(en))) ids.push(+m[1]);
      var lit = parts.reduce(function(a, b){ return b.length > a.length ? b : a; }, '');
      // Too generic to be safe: almost no words, or words only between holes.
      var letters = parts.join('').replace(/[^A-Za-zÀ-ÿ]/g, '').length;
      if (letters < 3 || (letters < 5 && !parts[0] && !parts[parts.length - 1])) continue;
      var src = '^';
      for (var k = 0; k < parts.length; k++) {
        src += esc(parts[k]);
        if (k < ids.length) src += '([\\s\\S]*?)';
      }
      try {
        RULES.push({re: new RegExp(src + '$'), ids: ids, es: T[i][1], lit: lit,
                    w: parts.join('').length});
      } catch (e) {}
    }
    RULES.sort(function(a, b){ return b.w - a.w; });
  }
  function fill(r, m){
    var got = {};
    for (var i = 0; i < r.ids.length; i++) got[r.ids[i]] = m[i + 1];
    return r.es.replace(/\{(\d+)(?::t|\?([^:}]*):([^}]*))?\}/g, function(all, n, a, b){
      var v = got[n] == null ? '' : got[n];
      if (/:t\}$/.test(all)) return tr(v) || v;
      if (a != null) { var c = v.trim(); return (c === '' || c === '1') ? a : b; }
      // A whole sentence in a hole (a server message after "Could not save: ")
      // is never somebody's track or tag: translate it too.
      if (v.length > 24 && / \S+ \S+ /.test(v)) return tr(v) || v;
      return v;
    });
  }

  // ── one string ───────────────────────────────────────────────────────────
  var CACHE = new Map();
  function look(core){
    var v = D[core];
    if (v != null) return v;
    if (CACHE.has(core)) return CACHE.get(core);
    var out = null;
    for (var x = 0; x < RX.length; x++)
      if (RX[x][0].test(core)) { out = core.replace(RX[x][0], RX[x][1]); break; }
    if (out == null && core.length < 600) {
      if (!RULES) compile();
      for (var i = 0; i < RULES.length; i++) {
        var r = RULES[i];
        if (core.indexOf(r.lit) < 0) continue;
        var m = r.re.exec(core);
        if (m) { out = fill(r, m); break; }
      }
    }
    if (CACHE.size > 20000) CACHE.clear();
    CACHE.set(core, out);
    return out;
  }
  // Whole string, leading and trailing whitespace kept; null if unknown.
  function tr(s){
    if (!s || !/[A-Za-z]{2}/.test(s)) return null;
    var lead = s.match(/^\s*/)[0], trail = s.match(/\s*$/)[0];
    var core = norm(s);
    if (!core) return null;
    var v = look(core);
    return v == null ? null : lead + v + (trail.length < s.length - lead.length ? trail : '');
  }

